const fn llm_preset(
    id: &'static str,
    engine_type: ProviderType,
    name: &'static str,
    description_key: &'static str,
    homepage: &'static str,
    api_key_url: &'static str,
    base_url: &'static str,
) -> ProviderPreset {
    ProviderPreset {
        id,
        engine_type,
        protocol: if matches!(engine_type, ProviderType::Anthropic) {
            "anthropic"
        } else {
            "openai_compatible"
        },
        category: if matches!(engine_type, ProviderType::OpenAiCompatible) {
            ProviderCategory::Aggregator
        } else {
            ProviderCategory::LlmOfficial
        },
        name,
        description_key,
        homepage_url: Some(homepage),
        api_key_url: Some(api_key_url),
        base_url,
        models_url: "",
        fields: LLM_KEY_MODEL,
        capabilities: LLM_TRANSLATION,
        auth_scheme: if matches!(engine_type, ProviderType::Anthropic) {
            AuthScheme::Anthropic
        } else {
            AuthScheme::Bearer
        },
        supported_platforms: BOTH_DESKTOPS,
        network_policy: NetworkPolicy::OfficialApi,
        stability: Stability::Stable,
    }
}

