pub fn preset_by_id(id: &str) -> Option<&'static ProviderPreset> {
    PRESETS.iter().find(|preset| preset.id == id)
}

pub fn presets_for_platform(macos: bool) -> Vec<&'static ProviderPreset> {
    PRESETS
        .iter()
        .filter(|preset| preset.available_on(macos))
        .collect()
}
